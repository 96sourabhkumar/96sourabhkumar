#!/usr/bin/env python3
"""Rebuild the projects table in README.md from the owner's public GitHub repos.

Runs inside GitHub Actions (see .github/workflows/update-repos.yml).
Everything between <!-- REPOS:START --> and <!-- REPOS:END --> is replaced.

Optional env vars:
  GH_USER        GitHub username (defaults to the repo owner)
  GITHUB_TOKEN   token for higher API rate limits
  EXCLUDE        comma-separated repo names to hide
  PINNED         comma-separated repo names to always list first, in this order
  MAX_REPOS      max rows in the table (default 30)
  INCLUDE_FORKS  "true" to list forks too (default false)
"""
import json, os, re, sys, urllib.request
from datetime import datetime, timezone

USER = os.environ.get("GH_USER") or os.environ.get("GITHUB_REPOSITORY_OWNER") or "sourabhkumar-96"
TOKEN = os.environ.get("GITHUB_TOKEN", "")
EXCLUDE = {s.strip().lower() for s in os.environ.get("EXCLUDE", "").split(",") if s.strip()}
EXCLUDE.add(USER.lower())  # the profile repo itself
PINNED = [s.strip() for s in os.environ.get("PINNED", "").split(",") if s.strip()]
MAX = int(os.environ.get("MAX_REPOS", "30"))
FORKS = os.environ.get("INCLUDE_FORKS", "false").lower() == "true"
README = os.environ.get("README_PATH", "README.md")
START, END = "<!-- REPOS:START -->", "<!-- REPOS:END -->"


def api(url):
    req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "profile-readme-bot"})
    if TOKEN:
        req.add_header("Authorization", f"Bearer {TOKEN}")
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def fetch():
    repos, page = [], 1
    while True:
        batch = api(f"https://api.github.com/users/{USER}/repos?per_page=100&page={page}&type=owner&sort=pushed")
        repos += batch
        if len(batch) < 100:
            return repos
        page += 1


def pretty(name):
    words = re.split(r"[-_]+", name)
    return " ".join(w if (w.isupper() or any(ch.isdigit() for ch in w)) else w.capitalize() for w in words if w)


def esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ").strip()


def ago(iso):
    return datetime.fromisoformat(iso.replace("Z", "+00:00")).strftime("%b %Y")


def main():
    repos = [r for r in fetch()
             if not r.get("private") and not r.get("archived")
             and (FORKS or not r.get("fork"))
             and r["name"].lower() not in EXCLUDE]
    rank = {n.lower(): i for i, n in enumerate(PINNED)}
    repos.sort(key=lambda r: (rank.get(r["name"].lower(), len(rank)), -datetime.fromisoformat(r["pushed_at"].replace("Z", "+00:00")).timestamp()))
    repos = repos[:MAX]

    rows = ["| Project | What it does | Stack | ⭐ | Updated |", "|:--|:--|:--|:-:|:-:|"]
    for r in repos:
        desc = esc(r.get("description")) or "<i>Description coming soon</i>"
        stack = [r["language"]] if r.get("language") else []
        stack += [t for t in (r.get("topics") or [])[:3] if t.lower() != (r.get("language") or "").lower()]
        rows.append(f"| [{pretty(r['name'])}]({r['html_url']}) | {desc} | {esc(' · '.join(stack)) or '—'} "
                    f"| {r.get('stargazers_count', 0)} | {ago(r['pushed_at'])} |")
    body = "\n".join(rows)
    stamp = datetime.now(timezone.utc).strftime("%d %b %Y")
    block = (f"{START}\n<!-- auto-generated by scripts/update_repos.py — edits here are overwritten -->\n\n"
             f"{body}\n\n<p align=\"right\"><sub>{len(repos)} public repos · auto-synced {stamp}</sub></p>\n{END}")

    text = open(README, encoding="utf-8").read()
    if START not in text or END not in text:
        sys.exit(f"Markers {START} / {END} not found in {README}")
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    # don't commit just because the date stamp / "x days ago" moved
    strip = lambda s: re.sub(r"auto-synced [^<]+", "", s)
    if strip(new) == strip(text):
        print("No repo changes.")
        return
    open(README, "w", encoding="utf-8").write(new)
    print(f"README updated with {len(repos)} repos.")


if __name__ == "__main__":
    main()
